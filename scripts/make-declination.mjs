// Builds www/js/declination.js: a magnetic-declination grid (World Magnetic Model) for India, the Gulf and Saudi Arabia,
// so the Qibla compass can correct the phone's magnetic heading to true north. Optional: on failure the app uses a small built-in table.
import fs from "node:fs";
import path from "node:path";
import { execSync } from "node:child_process";
import { createRequire } from "node:module";
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")), "..");
const out = path.join(root, "www", "js", "declination.js");
try {
  try { createRequire(import.meta.url)("geomagnetism"); } catch { execSync("npm install --no-save --no-audit --no-fund geomagnetism", { cwd: root, stdio: "inherit" }); }
  const geo = createRequire(import.meta.url)("geomagnetism");
  const model = geo.model(new Date());
  const lat0 = -5, lon0 = 30, step = 2.5, nlat = 23, nlon = 33, v = [];
  for (let i = 0; i < nlat; i++) for (let j = 0; j < nlon; j++) v.push(Math.round(model.point([lat0 + i * step, lon0 + j * step]).decl * 100) / 100);
  fs.writeFileSync(out, "/* Generated by scripts/make-declination.mjs (World Magnetic Model). */\nwindow.KPT_DECL = " + JSON.stringify({ lat0, lon0, step, nlat, nlon, v }) + ";\n");
  console.log("• declination grid written (Kochi ≈ " + model.point([10, 76.3]).decl.toFixed(2) + "°, Kuwait ≈ " + model.point([29.4, 48]).decl.toFixed(2) + "°)");
} catch (e) {
  console.warn("⚠ declination model unavailable (" + e.message + ") – using the built-in table");
}
