// Prepares adhan sounds and native permissions for Android & iOS.
// Run after `npx cap add android` / `npx cap add ios`, and again whenever you add adhan recordings:
//   npm run setup:native && npx cap sync
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")), "..");
const r = (...p) => path.join(root, ...p);
const log = (m) => console.log("• " + m);
const warn = (m) => console.warn("⚠ " + m);
const mk = (d) => fs.mkdirSync(d, { recursive: true });

function hasFfmpeg() { try { execFileSync("ffmpeg", ["-version"], { stdio: "ignore" }); return true; } catch { return false; } }
const ff = hasFfmpeg();
if (!ff) warn("ffmpeg not found – MP3s will be copied as-is, but iPhone adhan clips cannot be made. Install ffmpeg (https://ffmpeg.org) and run again.");

// ---------- 0. Phone plugins, Quran text, compass correction ----------
const run = (cmd) => { try { execFileSync("node", [r("scripts", cmd)], { stdio: "inherit", cwd: root }); } catch (e) { warn(cmd + " failed: " + e.message); } };
run("bundle-native.mjs");
if (!fs.existsSync(r("www", "quran", "quran.json"))) run("get-quran.mjs");
if (!/KPT_DECL = \{/.test(fs.readFileSync(r("www", "js", "declination.js"), "utf8"))) run("make-declination.mjs");
if (!fs.existsSync(r("www", "js", "native.js")) || fs.statSync(r("www", "js", "native.js")).size < 2000) throw new Error("Phone plugins were not bundled – the adhan would not work. See the error above.");

// ---------- 1. Audio ----------
// Loudness every 0.1 s: the adhan starts at the first moment (held for 0.5 s) within 12 dB of the loudest part.
function voiceStart(file) {
  if (!ff) return 0;
  try {
    const out = execFileSync("ffmpeg", ["-hide_banner", "-nostats", "-loglevel", "error", "-i", file, "-vn", "-t", "150", "-af",
      "aresample=8000,asetnsamples=800,astats=metadata=1:reset=1,ametadata=print:key=lavfi.astats.Overall.RMS_level:file=-", "-f", "null", "-"],
      { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
    const lv = [...out.matchAll(/RMS_level=(-?[\d.]+|-inf)/g)].map((m) => (m[1] === "-inf" ? -120 : parseFloat(m[1])));
    if (lv.length < 10) return 0;
    const sorted = [...lv].sort((x, y) => y - x), peak = sorted[Math.floor(sorted.length * 0.03)];
    for (let i = 0; i < lv.length - 5; i++) {
      if (lv.slice(i, i + 5).every((v) => v > peak - 12)) return Math.max(0, i * 0.1 - 0.3);
    }
    return 0;
  } catch (e) { return 0; }
}
const SRC = r("resources", "adhan-source");
const OUT_WWW = r("www", "audio"), OUT_AND = r("resources", "sounds", "android"), OUT_IOS = r("resources", "sounds", "ios");
[OUT_WWW, OUT_AND, OUT_IOS].forEach(mk);
const sources = fs.existsSync(SRC) ? fs.readdirSync(SRC).filter((f) => /\.(mp3|m4a|wav|aac|ogg|oga|opus|webm|flac)$/i.test(f)) : [];
if (!sources.length) warn("No adhan recordings in resources/adhan-source/. The app will use the built-in chime until you add them (see README).");
for (const f of sources) {
  const id = path.basename(f, path.extname(f)).toLowerCase().replace(/[^a-z0-9_]/g, "_");
  const inp = path.join(SRC, f), mp3 = path.join(OUT_WWW, `adhan_${id}.mp3`);
  if (ff) {
    // Find where the muezzin's voice really starts (skips crowd noise, talking and silence at the beginning),
    // then even out the volume. Max 4 minutes, audio only.
    const start = voiceStart(inp);
    if (start > 0.5) log(`${id}: skipping first ${start.toFixed(1)} s before the adhan starts`);
    const clean = `atrim=start=${start.toFixed(2)},asetpts=PTS-STARTPTS,afade=t=in:d=0.4,loudnorm=I=-16:TP=-1.5:LRA=11`;
    execFileSync("ffmpeg", ["-y", "-loglevel", "error", "-i", inp, "-vn", "-af", clean + ",afade=t=out:st=236:d=4", "-t", "240", "-ac", "1", "-ar", "44100", "-b:a", "96k", mp3]);
    // iOS notification sounds must be < 30 s: make a 29 s clip with a gentle fade-out.
    execFileSync("ffmpeg", ["-y", "-loglevel", "error", "-i", inp, "-vn", "-af", clean + ",afade=t=out:st=26:d=3", "-t", "29", "-ac", "1", "-ar", "22050", "-acodec", "pcm_s16le", path.join(OUT_IOS, `adhan_${id}.wav`)]);
  } else if (/\.mp3$/i.test(f)) fs.copyFileSync(inp, mp3);
  else { warn(`Skipped ${f} (needs ffmpeg to convert)`); continue; }
  fs.copyFileSync(mp3, path.join(OUT_AND, `adhan_${id}.mp3`));
  log(`Adhan prepared: ${id}`);
}
// Extra recordings (not in the built-in list) appear in the app automatically.
const KNOWN = ["makkah", "madinah", "azeez", "short", "makkah_maghrib", "istanbul", "kazakh", "fajr_malmo"];
const extra = sources.map((f) => path.basename(f, path.extname(f)).toLowerCase().replace(/[^a-z0-9_]/g, "_")).filter((id) => !KNOWN.includes(id));
const nice = (id) => id.replace(/_/g, " ").replace(/\b\w/g, (c) => c.toUpperCase());
fs.writeFileSync(r("www", "js", "adhans-extra.js"), "/* Generated by scripts/native-setup.mjs: extra adhans from resources/adhan-source/. */\nwindow.KPT_EXTRA_ADHANS = " +
  JSON.stringify(extra.map((id) => ({ id, en: nice(id), ml: nice(id), fajr: id.startsWith("fajr") || undefined }))) + ";\n");
if (extra.length) log(`Extra adhans added to the app: ${extra.join(", ")}`);
fs.copyFileSync(r("www", "audio", "chime.wav"), path.join(OUT_AND, "chime.wav"));
fs.copyFileSync(r("www", "audio", "chime.wav"), path.join(OUT_IOS, "chime.wav"));

// ---------- 2. Android ----------
const AND = r("android", "app", "src", "main");
if (fs.existsSync(AND)) {
  const raw = path.join(AND, "res", "raw"); mk(raw);
  for (const f of fs.readdirSync(OUT_AND)) fs.copyFileSync(path.join(OUT_AND, f), path.join(raw, f));
  const dr = path.join(AND, "res", "drawable"); mk(dr);
  fs.writeFileSync(path.join(dr, "ic_stat_prayer.xml"),
`<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">
  <path android:fillColor="#FFFFFFFF" android:pathData="M12,3C9,5.5 6,7 6,11h12C18,7 15,5.5 12,3zM11.5,0.5h1v2.5h-1zM4,11h2v10H4zM18,11h2v10h-2zM3,21h18v1.5H3zM7,12h10v9h-3v-3a2,2 0,0 0,-4 0v3H7z"/>
</vector>`);
  const mf = path.join(AND, "AndroidManifest.xml");
  let xml = fs.readFileSync(mf, "utf8");
  const perms = ["ACCESS_COARSE_LOCATION", "ACCESS_FINE_LOCATION", "POST_NOTIFICATIONS", "SCHEDULE_EXACT_ALARM", "RECEIVE_BOOT_COMPLETED", "VIBRATE", "WAKE_LOCK"];
  let add = "";
  for (const p of perms) if (!xml.includes(`android.permission.${p}"`)) add += `\n    <uses-permission android:name="android.permission.${p}" />`;
  if (!xml.includes("android.hardware.location.gps")) add += `\n    <uses-feature android:name="android.hardware.location.gps" android:required="false" />`;
  if (add) { xml = xml.replace(/<\/manifest>\s*$/, add.trimStart().replace(/^/, "    ") + "\n</manifest>\n"); fs.writeFileSync(mf, xml); }
  // Home-screen widget + native helper plugin (battery status, settings shortcuts)
  const appId = JSON.parse(fs.readFileSync(r("capacitor.config.json"), "utf8")).appId;
  const javaDir = path.join(AND, "java", ...appId.split("."));
  mk(javaDir);
  const NAT = r("native", "android");
  for (const f of fs.readdirSync(path.join(NAT, "java"))) {
    const src = fs.readFileSync(path.join(NAT, "java", f), "utf8").replace(/^package [\w.]+;/m, `package ${appId};`).replace(/com\.kerala\.prayertimes\.WIDGET_REFRESH/g, `${appId}.WIDGET_REFRESH`);
    fs.writeFileSync(path.join(javaDir, f), src);
  }
  const kt = path.join(javaDir, "MainActivity.kt"); if (fs.existsSync(kt)) fs.rmSync(kt);
  for (const sub of fs.readdirSync(path.join(NAT, "res"))) {
    const d = path.join(AND, "res", sub); mk(d);
    for (const f of fs.readdirSync(path.join(NAT, "res", sub))) fs.copyFileSync(path.join(NAT, "res", sub, f), path.join(d, f));
  }
  xml = fs.readFileSync(mf, "utf8");
  if (!xml.includes(".PrayerWidget")) {
    xml = xml.replace(/<\/application>/, `    <receiver android:name=".PrayerWidget" android:exported="false" android:label="@string/kpt_widget_name">
            <intent-filter>
                <action android:name="android.appwidget.action.APPWIDGET_UPDATE" />
            </intent-filter>
            <meta-data android:name="android.appwidget.provider" android:resource="@xml/kpt_widget_info" />
        </receiver>
    </application>`);
    fs.writeFileSync(mf, xml);
  }
  // Version number for Google Play (must go up with every upload) + don't fail release builds on lint warnings
  const gradle = r("android", "app", "build.gradle");
  if (fs.existsSync(gradle)) {
    let g = fs.readFileSync(gradle, "utf8");
    const run = parseInt(process.env.GITHUB_RUN_NUMBER || process.env.VERSION_CODE || "1", 10);
    g = g.replace(/versionCode\s+\d+/, `versionCode ${run}`).replace(/versionName\s+"[^"]*"/, `versionName "2.1.${run}"`);
    if (!g.includes("checkReleaseBuilds")) g += `\nandroid {\n    lint {\n        checkReleaseBuilds false\n        abortOnError false\n    }\n}\n`;
    fs.writeFileSync(gradle, g);
  }
  log("Android: sounds copied, notification icon, permissions, widget and native helper added");
} else log("Android platform not added yet (run: npx cap add android) – skipped");

// ---------- 3. iOS ----------
const IOS = r("ios", "App", "App");
if (fs.existsSync(IOS)) {
  const sd = path.join(IOS, "sounds"); mk(sd);
  const files = fs.readdirSync(OUT_IOS);
  for (const f of files) fs.copyFileSync(path.join(OUT_IOS, f), path.join(sd, f));
  // Register sounds in the Xcode project so they are bundled with the app.
  const pbx = r("ios", "App", "App.xcodeproj", "project.pbxproj");
  try {
    const xcode = (await import("xcode")).default;
    const proj = xcode.project(pbx); proj.parseSync();
    const group = proj.findPBXGroupKey({ name: "App" }) || proj.findPBXGroupKey({ path: "App" });
    const target = proj.getFirstTarget().uuid;
    let n = 0;
    for (const f of files) { const rel = `sounds/${f}`; if (!proj.hasFile(rel)) { proj.addResourceFile(rel, { target }, group); n++; } }
    fs.writeFileSync(pbx, proj.writeSync());
    log(`iOS: ${files.length} sound(s) in app bundle (${n} newly added to Xcode project)`);
  } catch (e) {
    warn("Could not update the Xcode project automatically. In Xcode, drag ios/App/App/sounds into the App group and tick 'Add to target: App'. (" + e.message + ")");
  }
  const plist = path.join(IOS, "Info.plist");
  let pl = fs.readFileSync(plist, "utf8");
  const keys = {
    NSLocationWhenInUseUsageDescription: "Your location is used to calculate exact prayer times and the Qibla direction.",
    NSMotionUsageDescription: "The compass is used to show the Qibla direction."
  };
  for (const [k, v] of Object.entries(keys)) if (!pl.includes(`<key>${k}</key>`)) pl = pl.replace(/<\/dict>\s*<\/plist>\s*$/, `\t<key>${k}</key>\n\t<string>${v}</string>\n</dict>\n</plist>\n`);
  fs.writeFileSync(plist, pl);
  log("iOS: location & compass permission texts added");
} else log("iOS platform not added yet (run on a Mac: npx cap add ios) – skipped");

console.log("\nDone. Now run:  npx cap sync");
